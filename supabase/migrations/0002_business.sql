-- Kin Kitchen business modules: recipes, orders, income, expenses, balance sheet,
-- BIR tax payments, tasks and saved dashboard views. Run after 0001_init.sql.
-- Nested lists (recipe lines, order items, payments) are jsonb on their parent row.

create table recipes (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users default auth.uid(),
  name text not null,
  "group" text,
  yield_qty numeric not null check (yield_qty > 0),
  yield_label text not null default 'pc',
  price numeric not null default 0 check (price >= 0),
  labor_cost numeric not null default 0 check (labor_cost >= 0),
  overhead_cost numeric not null default 0 check (overhead_cost >= 0),
  target_margin numeric not null default 40 check (target_margin between 0 and 95),
  lines jsonb not null default '[]',
  active boolean not null default true,
  notes text,
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  unique (user_id, name)
);

create table orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users default auth.uid(),
  number int generated by default as identity (start with 1001),
  customer text not null,
  contact text,
  channel text not null default 'Facebook',
  order_date date not null default current_date,
  due_date date not null,
  status text not null default 'pending' check (status in ('pending','baking','done','cancelled')),
  items jsonb not null default '[]',
  delivery_fee numeric not null default 0 check (delivery_fee >= 0),
  discount numeric not null default 0 check (discount >= 0),
  payments jsonb not null default '[]',
  stock_moves jsonb,
  done_at timestamptz,
  notes text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);
create index on orders (user_id, due_date);

create table income (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users default auth.uid(),
  date date not null,
  description text not null,
  channel text not null default 'Other',
  amount numeric not null check (amount > 0),
  notes text,
  created_at timestamptz default now()
);
create index on income (user_id, date desc);

create table expenses (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users default auth.uid(),
  date date not null,
  description text not null,
  category text not null,
  amount numeric not null check (amount > 0),
  payee text,
  source text not null default 'manual' check (source in ('manual','restock')),
  ingredient_id uuid references ingredients(id) on delete set null,
  notes text,
  created_at timestamptz default now()
);
create index on expenses (user_id, date desc);

create table balance_items (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users default auth.uid(),
  side text not null check (side in ('asset','liability','equity')),
  "group" text not null,
  name text not null,
  amount numeric not null default 0 check (amount >= 0),
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create table tax_payments (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users default auth.uid(),
  year int not null,
  form text not null check (form in ('1701Q','1701A')),
  quarter int check (quarter between 1 and 3),
  amount numeric not null check (amount > 0),
  paid_on date not null,
  reference text,
  created_at timestamptz default now(),
  check ((form = '1701Q') = (quarter is not null))
);

create table tasks (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users default auth.uid(),
  title text not null,
  area text not null default 'Other',
  repeat text not null default 'none' check (repeat in ('none','daily','weekly')),
  due_date date,
  weekday int check (weekday between 0 and 6),
  done_on date,
  notes text,
  created_at timestamptz default now()
);

create table dashboard_views (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users default auth.uid(),
  name text not null,
  metric text not null,
  "group" text not null,
  range text not null,
  created_at timestamptz default now(),
  unique (user_id, name)
);

-- keep updated_at fresh (touch_updated_at comes from 0001)
create trigger trg_touch before update on recipes for each row execute function touch_updated_at();
create trigger trg_touch before update on orders for each row execute function touch_updated_at();
create trigger trg_touch before update on balance_items for each row execute function touch_updated_at();

-- row level security: every row belongs to its owner
alter table recipes enable row level security;
alter table orders enable row level security;
alter table income enable row level security;
alter table expenses enable row level security;
alter table balance_items enable row level security;
alter table tax_payments enable row level security;
alter table tasks enable row level security;
alter table dashboard_views enable row level security;
create policy own_recipes on recipes for all using (user_id = auth.uid());
create policy own_orders on orders for all using (user_id = auth.uid());
create policy own_income on income for all using (user_id = auth.uid());
create policy own_expenses on expenses for all using (user_id = auth.uid());
create policy own_balance on balance_items for all using (user_id = auth.uid());
create policy own_tax on tax_payments for all using (user_id = auth.uid());
create policy own_tasks on tasks for all using (user_id = auth.uid());
create policy own_views on dashboard_views for all using (user_id = auth.uid());
